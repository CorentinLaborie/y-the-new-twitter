// Generates styles/tokens.css from styles/tokens.json (the Claude Design "Y" design system, DEC-075).
// Run with `npm run tokens`; `npm run tokens:check` fails when tokens.css is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'styles');
const source = JSON.parse(readFileSync(join(root, 'tokens.json'), 'utf8'));
const check = process.argv.includes('--check');

const declarations = [];

// Light theme only (rule R9): every colour has one value.
for (const token of source.color.tokens) {
  declarations.push(`  --color-${token.name}: ${token.value.light};`);
}
for (const token of source.spacing.tokens) {
  declarations.push(`  --space-${token.name.replace(/^space-/, '')}: ${token.value};`);
}
for (const token of source.radius.tokens) {
  declarations.push(`  --radius-${token.name.replace(/^radius-/, '')}: ${token.value};`);
}
for (const token of source.shadow.tokens) {
  declarations.push(`  --shadow-${token.name.replace(/^shadow-/, '')}: ${token.value};`);
}
for (const [family, stack] of Object.entries(source.type.families)) {
  declarations.push(`  --font-${family}: ${stack};`);
}
for (const group of source.type.groups) {
  for (const style of group.styles) {
    const base = `--type-${style.name}`;
    declarations.push(`  ${base}-size: ${style.fontSize};`);
    declarations.push(`  ${base}-line-height: ${style.lineHeight};`);
    declarations.push(`  ${base}-weight: ${style.fontWeight};`);
  }
}

const css = [
  `/* Generated by scripts/build-tokens.mjs from styles/tokens.json. Do not edit by hand. */`,
  `:root {`,
  ...declarations,
  `}`,
  ``,
].join('\n');

const target = join(root, 'tokens.css');
if (check) {
  const current = readFileSync(target, 'utf8');
  if (current !== css) {
    console.error('styles/tokens.css is out of date: run npm run tokens.');
    process.exit(1);
  }
  console.log('styles/tokens.css is up to date.');
} else {
  writeFileSync(target, css);
  console.log(`styles/tokens.css written (${declarations.length} declarations).`);
}
